def done(run):
    return mt.exit_code(run) == "0"


def wrap(text, run):
    return text if done(run) else rf"\pend{{{text}}}"


def evals(run, key):
    return [r for r in mt.rows(run) if key in r]


def steps_to(run, thresh=0.9):
    """Env steps (k) until the eval return first reaches thresh; '--' if not within the budget."""
    ev = evals(run, "eval_return")
    if not ev:
        return r"\nr" if not mt.planned(run) else r"\pend{$\cdot$}"
    hit = next((r["step"] for r in ev if r["eval_return"] >= thresh), None)
    if hit is not None:
        return f"{hit / 1e3:.0f}k"  # final once reached
    return "--" if done(run) else r"\pend{$>$" + f"{ev[-1]['step'] / 1e3:.0f}k" + "}"


def final_return(run, fmt="{:.2f}"):
    ev = evals(run, "eval_return")
    if not ev:
        return r"\nr" if not mt.planned(run) else r"\pend{$\cdot$}"
    return wrap(fmt.format(np.mean([r["eval_return"] for r in ev[-3:]])), run)


def probe(run, thresh=0.9):
    """Updates (k) until reward AUC > thresh; failures show '-- (final AUC)'."""
    ev = evals(run, "eval_auc")
    if not ev:
        return r"\nr" if not mt.planned(run) else r"\pend{$\cdot$}"
    hit = next((r["step"] for r in ev if r["eval_auc"] > thresh), None)
    last = np.mean([r["eval_auc"] for r in ev[-3:]])
    if hit is not None:
        # crossed the threshold but did not stay above it: show the final AUC as well
        return f"{hit / 1e3:g}k" + (rf"\,{{\tiny({last:.2f})}}" if last < thresh and done(run) else "")
    cell = rf"--\,{{\tiny({last:.2f})}}"
    return cell if done(run) else rf"\pend{{{cell}}}"


def rate(run):
    ev = evals(run, "eval_auc")
    return ev[-1]["eval_deter_rate"] if ev else None


def write(name, lines):
    (OUT / f"{name}.tex").write_text("% generated by paper/scripts/paper_tables.py; do not edit\n" + "\n".join(lines) + "\n")


def r2i_popgym(task, window=200_000):
    """R2I (official code): mean training-episode score over the last `window` env steps
    (its code logs no separate evaluation; at convergence the two agree within 0.04 for our models)."""
    path = mt.RUNS / f"r2i_agent/popgym_{task}/R2I/s0"
    sc = path / "scores.jsonl"
    if not sc.exists():
        return r"\pend{$\cdot$}"
    rows = [json.loads(l) for l in sc.read_text().splitlines() if l.strip()]
    rows = [r for r in rows if "episode/score" in r]
    if not rows:
        return r"\pend{$\cdot$}"
    last = rows[-1]["step"]
    v = np.mean([r["episode/score"] for r in rows if r["step"] >= last - window])
    exit_path = path / ".exit"
    fin = exit_path.exists() and exit_path.read_text().strip() == "0"
    return f"{v:.2f}" if fin else rf"\pend{{{v:.2f}}}"


